def L(id, kind, req, fac="", **kw):
    d = {"id": id, "kind": kind, "req": req, "fac": fac.split()}
    d.update(kw)
    return d


def T(name, sprite, team, **kw):
    """Trainer: team is a list of (pokemon identifier, level) or (identifier, level, {extra})."""
    d = {"name": name, "sprite": sprite, "team": team}
    d.update(kw)
    return d


def G(loc, leader, sprite, type_, badge, team, **kw):
    d = {"loc": loc, "leader": leader, "sprite": sprite, "type": type_, "badge": badge, "team": team}
    d.update(kw)
    return d


