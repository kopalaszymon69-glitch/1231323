COND_KEEP = re.compile(r"^(time-(morning|day|night)|season-.*|weather-.*|swarm-yes|radar-on|slot2-.*|radio-.*|"
                       r"story-progress-(hall-of-fame|national-dex|beat-elite-four-round-two|beat-red)|"
                       r"max-den-rarity-(common|rare)|trade-.*|item-.*|weekday-.*|starter-.*|coins-.*)$")
POSTGAME_CONDS = {"story-progress-hall-of-fame", "story-progress-national-dex",
                  "story-progress-beat-elite-four-round-two", "story-progress-beat-red"}


def merge_postgame(lst):
    """Fold post-game duplicates (same Pokémon/method/conditions) into a `post` level range."""
    base = {}
    result = []
    for item in lst:
        conds = item[5] if len(item) > 5 else []
        if any(c in POSTGAME_CONDS for c in conds):
            continue
        base[(item[0], item[1], tuple(conds))] = item
        result.append(item)
    for item in lst:
        conds = item[5] if len(item) > 5 else []
        if not any(c in POSTGAME_CONDS for c in conds):
            continue
        rest = tuple(c for c in conds if c not in POSTGAME_CONDS)
        b = base.get((item[0], item[1], rest))
        if b is not None:
            while len(b) < 6:
                b.append([])
            b.append([item[3], item[4]])
        else:
            cc = list(rest) + ["postgame"]
            result.append(item[:5] + [cc])
    result.sort(key=lambda x: (x[1], -x[2]))
    return result


def build_encounters(pokemon):
    loc = {r["id"]: r for r in rows("locations")}
    areas = {r["id"]: r for r in rows("location_areas")}
    area_count = defaultdict(set)
    for a in areas.values():
        area_count[a["location_id"]].add(a["id"])
    methods = {r["id"]: r["identifier"] for r in rows("encounter_methods")}
    slots = {r["id"]: r for r in rows("encounter_slots")}
    cond_vals = {r["id"]: r["identifier"] for r in rows("encounter_condition_values")}
    enc_cond = defaultdict(list)
    for r in rows("encounter_condition_value_map"):
        enc_cond[r["encounter_id"]].append(cond_vals[r["encounter_condition_value_id"]])
    version_region = defaultdict(list)
    for reg, vs in VERSION_SETS.items():
        for v in vs:
            version_region[v].append(reg)
    # agg[region][loc][(pid, method, conds)] -> {versions: {v: rarity_sum}, min, max}
    agg = defaultdict(lambda: defaultdict(dict))
    areas_seen = defaultdict(lambda: defaultdict(set))
    for r in rows("encounters"):
        v = int(r["version_id"])
        if v not in version_region:
            continue
        area = areas[r["location_area_id"]]
        lid = area["location_id"]
        slot = slots[r["encounter_slot_id"]]
        mname = methods[slot["encounter_method_id"]]
        mg = METHOD_GROUP.get(mname)
        if not mg:
            continue
        pid = r["pokemon_id"]
        if pid not in pokemon:
            base = None
            continue
        conds = tuple(sorted(c for c in enc_cond.get(r["id"], []) if COND_KEEP.match(c)))
        for reg in version_region[v]:
            key = (int(pid), mg, conds)
            e = agg[reg][lid].get(key)
            if not e:
                e = {"v": defaultdict(int), "min": 999, "max": 0}
                agg[reg][lid][key] = e
            e["v"][(v, area["id"])] += int(slot["rarity"] or 0) or 1
            e["min"] = min(e["min"], int(r["min_level"]))
            e["max"] = max(e["max"], int(r["max_level"]))
            areas_seen[reg][lid].add((v, area["id"]))
    out = {}
    for reg, locs in agg.items():
        out[reg] = {}
        for lid, entries in locs.items():
            ident = loc[lid]["identifier"]
            # Number of (version, area) combos that have any data for this location.
            vers = defaultdict(set)
            for (v, a) in areas_seen[reg][lid]:
                vers[v].add(a)
            nv = len(vers)
            lst = []
            for (pid, mg, conds), e in entries.items():
                total = 0.0
                for (v, a), rr in e["v"].items():
                    total += rr / max(1, len(vers[v]))
                weight = round(total / max(1, nv), 2)
                item = [pid, mg, weight, e["min"], e["max"]]
                if conds:
                    item.append(list(conds))
                lst.append(item)
            out[reg][ident] = merge_postgame(lst)
    with open(os.path.join(ROOT, "tools", "encounters.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, separators=(",", ":"))
    print("wrote tools/encounters.json", sum(len(v) for v in out.values()), "locations")
    # Location display names for the world builder.
    names = {r["location_id"]: r["name"] for r in rows("location_names") if r["local_language_id"] == EN}
    with open(os.path.join(ROOT, "tools", "location_names.json"), "w", encoding="utf-8") as f:
        json.dump({loc[l]["identifier"]: n for l, n in names.items() if l in loc}, f, ensure_ascii=False)


